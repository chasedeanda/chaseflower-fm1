"""Compile the approved expression atlases to bounded indexed row spans.

No runtime PNG decoder, image cache or scratch canvas. A character has one
60-colour palette and four 112px frames; transparent runs are omitted in XIP.
Studio's static stickers share those palettes and have independent pixel data.
"""
import sys
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SIZE, COLORS, FRAMES, STICKER = 112, 60, 4, 28
CHARACTERS = (("devil", (0x15, 0x0F, 0x0C)), ("cat", (0x19, 0x0F, 0x19)))


def array(ctype, name, values):
    rows = [", ".join(map(str, values[i:i + 24])) for i in range(0, len(values), 24)]
    return f"static const {ctype} {name}[] = {{\n    " + ",\n    ".join(rows) + "\n};"


def generate(out):
    lines = ["/* Generated by tools/gen_mascots.py from approved mascot artwork. */",
             f"enum {{ CFM_ART_W={SIZE}, CFM_ART_H={SIZE}, CFM_ART_COLORS={COLORS}, CFM_ART_FRAMES={FRAMES} }};",
             "typedef struct { const uint32_t *rgb; const uint8_t *data; const uint16_t *rows; } cfm_art_t;",
             f"enum {{ CFM_STICKER_SIZE={STICKER} }};",
             "typedef struct { const uint32_t *rgb; const uint8_t *pixels; } cfm_sticker_t;"]
    total = 0
    for name, bg in CHARACTERS:
        source = Image.open(ROOT / "assets" / "mascots" / f"{name}-expressions.png").convert("RGBA")
        if source.width != source.height or source.width % 2:
            raise ValueError(f"{name}: expected an even square 2x2 atlas")
        cell = source.width // 2
        frames, masks = [], []
        for face in range(FRAMES):
            x, y = face % 2 * cell, face // 2 * cell
            image = source.crop((x, y, x + cell, y + cell)).resize((SIZE, SIZE), Image.Resampling.LANCZOS)
            masks.append(image.getchannel("A"))
            base = Image.new("RGBA", (SIZE, SIZE), (*bg, 255))
            frames.append(Image.alpha_composite(base, image).convert("RGB"))
        strip = Image.new("RGB", (SIZE, SIZE * FRAMES), bg)
        for face, image in enumerate(frames):
            strip.paste(image, (0, face * SIZE))
        indexed = strip.quantize(colors=COLORS, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
        pal = indexed.getpalette()
        rgb = [(pal[i * 3] << 16) | (pal[i * 3 + 1] << 8) | pal[i * 3 + 2] for i in range(COLORS)]
        pixels = indexed.load()
        data, offsets = [], []
        for face, mask in enumerate(masks):
            alpha = mask.load()
            for y in range(SIZE):
                offsets.append(len(data))
                used = [x for x in range(SIZE) if alpha[x, y] >= 20]
                first, length = (used[0], used[-1] - used[0] + 1) if used else (0, 0)
                data.extend((first, length))
                data.extend(pixels[x, face * SIZE + y] + 1 if alpha[x, y] >= 20 else 0
                            for x in range(first, first + length))
        if len(data) >= 65536:
            raise ValueError(f"{name}: row offsets exceed 16 bits")
        prefix = "CFM_" + name.upper()
        lines += [array("uint32_t", prefix + "_RGB", rgb), array("uint16_t", prefix + "_ROWS", offsets),
                  array("uint8_t", prefix + "_DATA", data)]
        sample = [(2 * i + 1) * SIZE // (2 * STICKER) for i in range(STICKER)]
        idle_alpha = masks[0].load()
        sticker = [pixels[x, y] + 1 if idle_alpha[x, y] >= 20 else 0 for y in sample for x in sample]
        lines.append(array("uint8_t", prefix + "_STICKER", sticker))
        if name == "devil":
            lines += [array("uint16_t", "CFM_BOOT_ROWS", offsets[:SIZE]),
                      array("uint8_t", "CFM_BOOT_DATA", data[:offsets[SIZE]]),
                      "static const cfm_art_t CFM_BOOT_ART = {CFM_DEVIL_RGB, CFM_BOOT_DATA, CFM_BOOT_ROWS};"]
        total += len(data) + 2 * len(offsets) + 4 * len(rgb)
        print(f"Mascot {name}: {len(data)} row-span bytes, {len(offsets) * 2} row-offset bytes, {COLORS} colours")
    lines.append("static const cfm_art_t CFM_ART[] = {\n"
                 "    {CFM_DEVIL_RGB, CFM_DEVIL_DATA, CFM_DEVIL_ROWS},\n"
                 "    {CFM_CAT_RGB, CFM_CAT_DATA, CFM_CAT_ROWS}\n};")
    lines.append("static const cfm_sticker_t CFM_STICKERS[] = {\n"
                 "    {CFM_DEVIL_RGB, CFM_DEVIL_STICKER},\n"
                 "    {CFM_CAT_RGB, CFM_CAT_STICKER}\n};")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"Mascot art: {total} linked data bytes; no runtime decode buffer")


if __name__ == "__main__":
    generate(Path(sys.argv[1]))
