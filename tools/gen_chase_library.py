"""Reproducible ChaseFlower audition library. No network access or device writes.

32 original FM voices, 34 unchanged CC0 Aquanode voices, 56 original VA patches,
and eight drum kits derived from the existing GPL drum designs. The catalog gives
each sound a stable ID; genre placement is provisional until Chase auditions it.
Run normally to regenerate, or --check to verify the committed outputs.
"""
import hashlib
import json
import re
import sys
from pathlib import Path

from gen_fm6_patches import op, voice, pack

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'firmware/src'
BANKS = json.loads((ROOT / 'assets/sounds/chase3-design.json').read_text())
CHECK = '--check' in sys.argv
catalog = []


def emit(path, body):
    text = '/* SPDX-License-Identifier: GPL-3.0-only\n * Generated by tools/gen_chase_library.py. Aquanode voice bytes: CC0-1.0; see assets/sounds/candidates/aquanode. */\n' + body
    path = ROOT / path
    if CHECK:
        assert path.read_text() == text, f'stale generated file: {path}'
    else:
        path.write_text(text)


def short(name):
    return name.upper().replace('BRUSH-LIKE', 'BRUSH').replace('NYLON-LIKE', 'NYLON')[:12].rstrip()


def fm_original(name, family, bank, variant):
    """Three FM pairs, or additive organ. Envelopes differ by instrument family."""
    sustained = family in ('pad', 'choir', 'strings', 'organ')
    bell = family in ('bell', 'mallet')
    attack = 40 + bank % 3 * 5 + variant * 3 if sustained else 98
    release = 32 + variant * 2 if sustained else 48 + variant * 3
    decay = 23 + variant * 3 if family == 'ep' else 34 + variant * 3
    sustain = 91 if sustained else 0
    ops = []
    for pair in range(3):
        ratio = (1, 2, 1)[pair] if not bell else (1, 2, 3)[pair]
        ops += [op(r=(attack, decay, 30, release), l=(99, 88, sustain, 0),
                   ol=(88, 76, 65)[pair], fc=ratio, det=(6, 9, 7)[pair], kvs=2, rs=2)]
        mr = (1, 3, 7)[pair] if family == 'ep' else (2, 3, 5)[pair] if bell else (1, 2, 1)[pair]
        level = (49, 38, 28)[pair] + variant * 3 + (8 if bell else 0)
        ops += [op(r=(min(99, attack+7), decay+16, 35, release+4),
                   l=(99, 64, 52 if sustained else 0, 0), ol=level, fc=mr,
                   ff=20+variant*5 if bell and pair == 1 else 0, kvs=4, rs=2)]
    if family == 'organ':
        ops = [op(r=(94, 80, 80, 78), l=(99, 99, 99, 0),
                  ol=lev, fc=ratio, kvs=1) for lev, ratio in zip((78, 64, 53, 45, 37, 30), (1, 2, 3, 4, 6, 8))]
    v = voice(name[:10].upper(), 32 if family == 'organ' else 5, ops,
              fb=0 if bell else 1, lfs=18+bank, lfd=35,
              lpmd=2 if sustained else 0, lfw=0, lpms=1)
    return pack(v)


FAMILIES = [
    ['ep', 'ep', 'ep', 'bell'], ['pad', 'choir', 'strings', 'pad'],
    ['ep', 'ep', 'organ', 'bell'], ['pad', 'choir', 'pad', 'strings'],
    ['bell', 'choir', 'pad', 'bell'], ['stab', 'organ', 'organ', 'stab'],
    ['mallet', 'mallet', 'mallet', 'bell'], ['pad', 'stab', 'pluck', 'pluck'],
]


def aquanode():
    base = ROOT / 'assets/sounds/candidates/aquanode'
    audit = json.loads((base / 'source-audit.json').read_text())
    seen, choices = set(), []
    for r in audit:
        if not r['included_for_audition']:
            continue
        b = (base / Path(r['path']).name).read_bytes()
        assert hashlib.sha256(b).hexdigest() == r['sha256']
        assert len(b) == 4104 and all(x < 128 for x in b[6:-1]) and sum(b[6:-1]) % 128 == 0
        for i, name in enumerate(r['names']):
            pk = b[6+i*128:6+(i+1)*128]
            if name.lower() == 'default' or pk[:118] in seen:
                continue
            seen.add(pk[:118])
            choices.append((list(pk), dict(source='Aquanode', source_bank=Path(r['path']).name,
                                          source_slot=i+1, original_name=name, revision=r['revision'], license='CC0-1.0')))
    assert len(choices) == 80
    # Stable first-release selection by source slot: fast/crackle for Dusty Room, fades for Tape,
    # flute/reed for Night Jazz, long/fill for Soft Focus, sweep/swell for Dub. Generic names
    # remain exploratory. Leave the explicitly named bass/sub voices in the offline candidate banks.
    order = [2,3,4,48, 5,6,7,8, 18,19,45,46, 9,10,11,49,
             22,23,24,25, 1,17,20,21, 26,27,39,40, 28,33,34,58]
    assert len(set(order)) == 32
    selected = [choices[i-1] for i in order]
    assert all('bass' not in src['original_name'].lower() and 'sub' not in src['original_name'].lower()
               for _, src in selected)
    return selected


fm, fm_rows, fm_banks = [], [], []
aq = aquanode()
for bank, b in enumerate(BANKS):
    for slot in range(8):
        if slot < 4:
            name = short(b['chords'][slot])
            pk = fm_original(name, FAMILIES[bank][slot], bank, slot)
            source = dict(source='ChaseFlower original FM design', license='GPL-3.0-only')
        else:
            k = bank*4+slot-4
            pk, source = aq[k]
            # Keep imported patches identifiable; do not pretend an unheard voice is a named acoustic instrument.
            name = ('AQ%02d ' % (k+1) + source['original_name'].upper())[:12]
        i = len(fm)
        fm.append(pk)
        fm_rows.append('    FM6_PR(%s, FM6_CHASE_SLOT + %d, 0, FX(0, 0, 0, 0)),' % (json.dumps(name), i))
        fm_banks.append(bank+1)
        catalog.append(dict(id='CF3-F%03d' % (i+1), name=name, bank=b['name'], bank_id=bank+1,
                            part='chord/layer', engine='FM6', factory_index=31+i, **source))


def va_patch(name, bank, slot, bass):
    low = name.lower()
    pluck = bass and slot == 1 and bank in (0, 2, 6) or any(t in low for t in ('pluck', 'chime', 'bell', 'mallet', 'kalimba', 'marimba', 'thumb'))
    organ = 'organ' in low
    reed = any(t in low for t in ('reed', 'flute', 'wire'))
    cut = (48, 56, 67, 62, 94, 45, 80, 68)[bank] + slot*2
    atk, dec, sus, rel = (1, 82+slot*3, 0 if pluck else 108, 36+slot*5) if bass else (
        (1, 94, 0, 86) if pluck else (4, 70, 127, 36) if organ else (62+bank*3, 88, 110, 94+slot*3))
    if bass:
        waves = [('SIN', 88, 0, 0), ('TRI', 82, 0, 0), ('PWM', 62, 0, 0)]
        w, lev, coarse, fine = waves[slot]
        osc = [f'OSC(0, {w}, {lev}, {coarse}, {fine})', f'OSC(1, SIN, {18+bank}, 12, 0)']
        cut = 38+bank*3+slot*7
        # Distinct bass constructions, rather than eight copies of the same three macros.
        if slot == 0 and bank in (1, 3):
            osc[1] = f'OSC(1, TRI, {16+bank}, 0, 3)'
        if slot == 1 and bank == 1:
            osc = ['OSC(0, TRI, 74, 0, -3)', 'OSC(1, TRI, 26, 0, 3)']
        if slot == 1 and bank in (3, 5, 7):
            osc = ['OSC(0, SQR, 69, 0, 0)', f'O_(0, SHAPE), {34+bank*5}', 'OSC(1, SIN, 20, 0, 0)']
        if slot == 1 and bank == 4:
            osc = ['OSC(0, SIN, 65, 0, 0)', 'OSC(2, SIN, 0, 12, 0)',
                   'OSC(3, SIN, 18, 0, 0)', 'VA_RING4, 1']
        if slot == 2 and bank == 0:
            osc = ['OSC(0, SAW, 58, 0, 0)', 'OSC(1, SIN, 31, 0, 0)']
        if slot == 2 and bank == 1:
            atk, sus, rel = 62, 110, 64
        if slot == 2 and bank == 3:
            osc = ['OSC(0, PWM, 54, 0, -3)', 'OSC(1, TRI, 38, 0, 3)']
        if slot == 2 and bank == 5:
            osc = ['OSC(0, SQR, 72, 0, 0)', 'O_(0, SHAPE), 38', 'OSC(1, SIN, 18, 0, 0)']
        if slot == 2 and bank == 6:
            osc = ['OSC(0, TRI, 78, 0, 0)', 'OSC(1, SIN, 33, 12, 0)']
        if slot == 2 and bank == 7:
            osc = ['OSC(0, SAW, 43, 0, -11)', 'OSC(1, SAW, 43, 0, 11)', 'OSC(2, SIN, 20, -12, 0)']
    elif pluck:
        osc = [f'OSC(0, TRI, {58+slot*3}, 0, 0)', f'OSC(1, SIN, {25+bank}, 12, {bank%4})']
    elif organ:
        osc = ['OSC(0, SIN, 61, 0, 0)', 'OSC(1, SIN, 37, 12, 0)', 'OSC(2, SIN, 19, 19, 0)']
    elif reed:
        osc = ['OSC(0, SQR, 53, 0, -3)', 'OSC(1, TRI, 39, 0, 3)']
    else:
        w = 'PWM' if bank in (0, 2, 7) else 'SAW'
        osc = [f'OSC(0, {w}, {48+slot*2}, 0, -{4+bank%4})', f'OSC(1, TRI, {43+slot}, 0, {4+bank%4})',
               f'OSC(2, SIN, {18+bank}, 12, 0)']
    res = 6+slot*4+(8 if bank==5 else 0)
    fenv = 22 if pluck else 6
    if bass and bank == 5 and slot == 2:
        res, fenv = 48, 34
    drive, det = (5+bank if bass else 3 if bank<2 else 0), (0 if bass or organ else 10+bank)
    parts = osc + [f'FLT(LP, {cut}, {res}, {fenv})', f'VA_DRIVE, {drive}', f'VA_DETUNE, {det}',
                    f'ENV1({atk}, {dec}, {sus}, {rel})', f'ENV2({atk}, 82, 40, {rel})', 'VA_VEL, 65']
    if not bass:
        parts += [f'VA_FSPREAD, {20+bank*7+slot*3}', f'LFO(0, {19+bank*3+slot}, 0, 127, 0)',
                  f'M_(0, VS_LFO1, VD_CUT, {4+slot})']
        if bank in (0, 1):
            parts += ['MODE(3, NOISE)', 'O_(3, WAVE), VN_VINYL', f'O_(3, LEVEL), {8+slot*2}',
                      'O_(3, SHAPE), 24', 'O_(3, KTRK), 0', 'LFO(1, 29, 0, 70, 0)',
                      'M_(1, VS_LFO1 + 1, VD_PITCH, 1)']
        if bank in (3, 4):
            parts += ['MODE(0, MORPH)', f'O_(0, SHAPE), {28+slot*12}', 'LFO(1, 17, 1, 127, 0)',
                      'M_(1, VS_LFO1 + 1, VD_SHP1, 16)']
    else:
        parts += ['M_(0, VS_VEL, VD_CUT, 12)']
    return ', '.join(parts)+', 0xFF', [cut, res, fenv, drive, 64, det, atk, rel], [atk, dec, sus, rel]


va_defs, va_rows, va_ptrs, va_banks, va_bass = [], [], [], [], []
for bank, b in enumerate(BANKS):
    for slot, longname in enumerate(b['chords'][8:] + b['bass']):
        bass = slot >= 4
        name, i = short(longname), len(va_rows)
        patch, macro, env = va_patch(longname, bank, slot-4 if bass else slot, bass)
        va_defs.append(f'static const uint8_t CHASE_VAP_{i}[] = {{{patch}}};')
        va_rows.append('    {%s, {%s}, {%s}, 0, %d, FX(0, 0, 0, 0)},' %
                       (json.dumps(name), ', '.join(map(str, macro)), ', '.join(map(str, env)), bass))
        va_ptrs.append(f'CHASE_VAP_{i}')
        va_banks.append(bank+1)
        va_bass.append(int(bass))
        catalog.append(dict(id='CF3-V%03d' % (i+1), name=name, bank=b['name'], bank_id=bank+1,
                            part='bass' if bass else 'chord/layer', engine='VA', factory_index=37+i,
                            source='ChaseFlower original VA design', license='GPL-3.0-only'))


# Two small additions use the last existing FM slots; the original 128 catalog records stay in order.
extras = []
extra_trims = []
extra_bank = ROOT / 'assets/sounds/candidates/aquanode/Aquanode Presets 4.syx'
extra_data = extra_bank.read_bytes()
assert hashlib.sha256(extra_data).hexdigest() == 'dbd63b38ca1dbfc2a05e4f1278821d14e8128f4906fce0c39d50aa7899a5ce2a'
for slot, original, name, trim in [(26, 'DX SAX', 'AQ33 DX SAX', 0), (29, 'DX FULLFLU', 'AQ34 FULLFLU', 12)]:
    pk = list(extra_data[6+(slot-1)*128:6+slot*128])
    assert bytes(pk[118:128]).decode().strip() == original
    assert all(pk[:118] != old[:118] for old in fm)
    i = len(fm)
    fm.append(pk)
    fm_rows.append('    FM6_PR(%s, FM6_CHASE_SLOT + %d, 0, FX(0, 0, 0, 0)),' % (json.dumps(name), i))
    fm_banks.append(9)  # Existing; leave the eight style banks' 12 chord / 3 bass choices intact.
    extra_trims.append(trim)
    extras.append(dict(id=f'CF3-F{i+1:03}', name=name, bank='Existing', bank_id=9, part='chord/layer',
                       engine='FM6', factory_index=31+i, source='Aquanode', source_bank=extra_bank.name,
                       source_slot=slot, original_name=original, revision='f0e59287c9991038f688c5e7457db77117638124',
                       license='CC0-1.0'))

meta = '#pragma once\n#define CHASE_FM_BASE 31u\n#define CHASE_VA_BASE 37u\n#define CHASE_FM_LEGACY_N 64u\n#define CHASE_FM_N 66u\n#define CHASE_VA_N 56u\n'
levels = json.loads((ROOT/'assets/sounds/chase3-levels.json').read_text())['sounds']
fm_trims = [levels['CF3-F%03d' % (i+1)]['half_db_trim'] for i in range(64)] + extra_trims
meta += 'static const int8_t CHASE_FM_TRIM[] = {'+', '.join(map(str, fm_trims))+'};\n'
meta += 'static const int8_t CHASE_VA_TRIM[] = {'+', '.join(str(levels['CF3-V%03d' % (i+1)]['half_db_trim']) for i in range(56))+'};\n'
meta += 'static const uint8_t CHASE_FM_BANK[] = {'+', '.join(map(str, fm_banks))+'};\n'
meta += 'static const uint8_t CHASE_VA_BANK[] = {'+', '.join(map(str, va_banks))+'};\n'
meta += 'static const uint8_t CHASE_VA_BASS[] = {'+', '.join(map(str, va_bass))+'};\n'
meta += 'static const char *const CHASE_BANK_NAMES[] = {"All", '+', '.join(json.dumps(b['name']) for b in BANKS)+', "Existing", "User"};\n'
emit('firmware/src/chase_meta.h', meta)
emit('firmware/src/chase_fm_data.h', 'static const uint8_t CHASE_FM_PATCHES[CHASE_FM_N][128] = {\n'+
     '\n'.join('    {'+', '.join(map(str, p))+'},' for p in fm)+'\n};\n')
emit('firmware/src/chase_fm_rows.h', '\n'.join(fm_rows)+'\n')
emit('firmware/src/chase_fm_names.h', ', '.join(json.dumps('C'+str(i+1)) for i in range(len(fm)))+',\n')
emit('firmware/src/chase_va_defs.h', '\n'.join(va_defs)+'\n')
emit('firmware/src/chase_va_rows.h', '\n'.join(va_rows)+'\n')
emit('firmware/src/chase_va_ptrs.h', ', '.join(va_ptrs)+',\n')

# Eight distinct kits, designed from the inherited oscillator/noise drum building blocks.
# Keep the six upstream kit definitions byte-for-byte intact; generated additions are separate.
text = (OUT / 'drum_kits.c').read_text()
old = re.findall(r'^\s+DS\(([^\n]+)\)', text, re.M)
assert len(old) == 6*18, len(old)
kit_names = ['Dust', 'Tape', 'Brush', 'Air', 'Glass', 'Dub', 'Wood', 'Chill']
kit_ctrl = [(36,42,3,10,8,70),(25,35,4,9,16,85),(28,50,1,0,22,88),(22,28,1,0,42,98),
            (38,18,1,0,28,92),(34,22,1,0,35,94),(30,55,1,0,18,83),(46,15,2,12,14,80)]
kit_rows=[]
for bank, name in enumerate(kit_names):
    src = (2,2,3,1,0,1,3,0)[bank]
    rows=[]
    for i in range(18):
        a=[v.strip() for v in old[src*18+i].split(',')]
        assert len(a)==22
        role=i%9
        def adj(k, v): a[k]=str(max(0,min(127,int(a[k])+v)))
        # Darker noise, different drum lengths and transient/body balance per kit and role.
        adj(13, (-14,-9,-18,-12,3,-22,-8,-4)[bank])
        adj(10, (-7,-2,-18,8,1,12,-8,-3)[bank] if role in (0,5) else -(bank%4))
        adj(15, (-8,-3,-15,5,8,3,-11,-4)[bank])
        adj(19, -22 if bank in (0,1,2,3) else -8)
        adj(20, -20 if bank in (2,3,4,6) else -8)
        adj(21, -5 if role in (2,3,4,8) else -2)
        if bank==2 and role in (1,2):
            a[0],a[1],a[2]='DSW_SINE','DSN_WHITE','DSF_LP'
            a[12]='20'; a[16]='98'; a[15]='94'; a[3]='0'
        if bank==4 and role in (6,7):
            a[0]='DSW_FM'; a[1]='DSN_NONE'; a[7]='9889'; a[10]='92'; a[12]='70'
        if bank==6 and role in (0,5,6):
            a[0]='DSW_SINE'; a[1]='DSN_WHITE'; adj(16,-35); adj(19,-20)
        if role in (0,5) and int(a[5]): a[5]=str(int(a[5])+(-20,-12,16,-30,22,-42,28,4)[bank])
        rows.append('        DS('+', '.join(a)+'),')
    kit_rows.append('    {"'+name+'",\n     {\n'+'\n'.join(rows[:9])+'\n     },\n     {\n'+'\n'.join(rows[9:])+
                    '\n     }, '+', '.join(map(str,kit_ctrl[bank]))+'},')
    catalog.append(dict(id=f'CF3-D{bank+1:03}', name=name, bank=BANKS[bank]['name'], bank_id=bank+1,
                        part='drums', engine='DRUM', kit_index=14+bank,
                        source='ChaseFlower design from CoralFlower drum synthesis', license='GPL-3.0-only'))
emit('firmware/src/chase_drum_rows.h','\n'.join(kit_rows)+'\n')

catalog.extend(extras)
assert len(catalog)==130
assert len({(r['engine'],r['name']) for r in catalog})==130
