"""Bounded four-level Inter Tight faces for the indexed native renderer."""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
root = Path(__file__).resolve().parents[1]
out = Path(sys.argv[1])
lines = ['/* Generated by tools/gen_native_font.py; Inter Tight, SIL OFL 1.1. */',
         'typedef struct { uint32_t off; int8_t x,y; uint8_t w,h,adv; } cfn_glyph_t;',
         'typedef struct { const cfn_glyph_t *g; const uint8_t *bits; } cfn_font_t;']
for size in (11,12,14,16,32,64):
    font=ImageFont.truetype(str(root/'assets/fonts/InterTight[wght].ttf'), size, layout_engine=ImageFont.Layout.BASIC)
    font.set_variation_by_axes([400 if size==11 else 600 if size>=14 else 500])
    data=[]; glyphs=[]
    for code in range(32,127):
        ch=chr(code)
        # The 64px face serves chord roots and the Click On/Off status only.
        # Keep conservative numeric/accidental coverage; other strings use
        # the complete 32px face through cfn_face(), rather than blank glyphs.
        if size==64 and ch not in ' ABCDEFGb#0123456789./-?OnfEXT':
            glyphs.append((0,0,0,0,0,0))
            continue
        x,y,x1,y1=font.getbbox(ch,anchor='ls'); w,h=x1-x,y1-y
        im=Image.new('L',(max(w,1),max(h,1))); d=ImageDraw.Draw(im)
        d.text((-x,-y),ch,font=font,anchor='ls',fill=255)
        bits=[(im.getpixel((a,b))*3+127)//255 for b in range(h) for a in range(w)]
        glyphs.append((len(data),x,y,w,h,round(font.getlength(ch))))
        for i in range(0,len(bits),4):
            v=0
            for j,b in enumerate(bits[i:i+4]): v|=b<<(6-2*j)
            data.append(v)
    lines.append(f'static const uint8_t CFN_{size}_BITS[] = {{'+','.join(map(str,data))+'};')
    lines.append(f'static const cfn_glyph_t CFN_{size}_G[] = {{'+','.join('{'+','.join(map(str,g))+'}' for g in glyphs)+'};')
    lines.append(f'static const cfn_font_t CFN_{size} = {{CFN_{size}_G, CFN_{size}_BITS}};')
    print(f'HOME Inter Tight {size}px: {len(data)} four-level bitmap bytes, {len(glyphs)} glyphs')
# The supplied CORD boot mark uses one fixed 45px tracked word, rather than a
# complete extra font atlas. Keep its exact bounded bitmap in the same licence.
font=ImageFont.truetype(str(root/'assets/fonts/InterTight[wght].ttf'),45,layout_engine=ImageFont.Layout.BASIC)
font.set_variation_by_axes([700])
letters='CORD';gap=7;width=sum(round(font.getlength(c)) for c in letters)+gap*3
top=min(font.getbbox(c,anchor='ls')[1] for c in letters);height=-top
im=Image.new('1',(width,height));d=ImageDraw.Draw(im);d.fontmode='1';x=0
for c in letters:
    d.text((x,-top),c,font=font,anchor='ls',fill=1);x+=round(font.getlength(c))+gap
bits=[int(im.getpixel((x,y))!=0) for y in range(height) for x in range(width)];data=[]
for i in range(0,len(bits),8):
    v=0
    for j,b in enumerate(bits[i:i+8]):v|=b<<(7-j)
    data.append(v)
lines.append(f'enum {{ CFN_CORD_W={width}, CFN_CORD_H={height} }};')
lines.append('static const uint8_t CFN_CORD_BITS[] = {'+','.join(map(str,data))+'};')
out.parent.mkdir(parents=True,exist_ok=True);out.write_text('\n'.join(lines)+'\n')
