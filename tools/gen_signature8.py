    is_fm = i in (0, 2, 6)
    factory = 97 + fm_index if is_fm else 93 + va_index
    CATALOG.append(dict(id=f'SIG8-{i+1:03}', name=name, bank_id=i+1,
                        engine='FM6' if is_fm else 'VA', factory_index=factory,
                        optional_fx=FX[i], license='GPL-3.0-only',
                        recipe_source='docs/signature8/BRIEF.md', default_fx='dry'))
    if is_fm: fm_index += 1
    else: va_index += 1
