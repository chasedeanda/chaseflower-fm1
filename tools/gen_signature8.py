def emit(path, body):
    path = ROOT / path
    text = '/* SPDX-License-Identifier: GPL-3.0-only; generated by tools/gen_signature8.py. */\n' + body
    if CHECK:
        assert path.read_text() == text, f'stale: {path}'
    else:
        path.write_text(text)

